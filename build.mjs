#!/usr/bin/env node
/**
 * Build the browser bundle for the dsh-screencapture client half.
 *
 * The Harness module loader serves exactly one plain-JavaScript file per client
 * plugin (`dsh.client` -> `./client`). Keeping the source split by concern and
 * concatenating it inside one factory body gives us normal file-level editing
 * without a bundler, while the emitted file stays a self-contained lazy factory
 * that only requires `react` from the platform module table.
 *
 * Usage: node build.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const ORDER = ['00-shared.js', '10-overlay.js', '20-settings.js', '30-entry.js']

const pieces = ORDER.map((name) => {
  const source = readFileSync(join(root, 'src', 'client', name), 'utf8')
  return `\n/* ============================== ${name} ============================== */\n${source}`
})

const bundle = `/* Generated by build.mjs — edit src/client/*.js, then run: node build.mjs */
window.__ModuleLoader__.load({
  id: "dsh-screencapture",
  factory: function (require) {
    const React = require("react");
    const h = React.createElement;${pieces.join('')}

    return { apply: apply, inject: inject };
  },
});
`

mkdirSync(join(root, 'lib'), { recursive: true })
writeFileSync(join(root, 'lib', 'client.js'), bundle)
console.log(`built lib/client.js (${Buffer.byteLength(bundle)} bytes)`)
